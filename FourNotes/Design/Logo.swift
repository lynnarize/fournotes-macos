    @Environment(\.palette) private var p
    var logoSize: CGFloat = 40
    var fontSize: CGFloat = 21

    var body: some View {
        HStack(spacing: 9) {
            Logo(size: logoSize)
            Text("Four Notes")
                .font(FN.font(fontSize, .bold))
                .tracking(-0.4)
                .foregroundStyle(p.text)
                .fixedSize()
        }
    }
}
